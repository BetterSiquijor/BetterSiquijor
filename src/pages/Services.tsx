import Section from '../components/ui/Section';
import { useParams, Link } from 'react-router';
import { Heading } from '../components/ui/Heading';
import { Text } from '../components/ui/Text';
import {
  serviceCategories,
  getCategorySubcategories,
  type Subcategory,
  type CategoryIndex,
} from '../data/yamlLoader';
import CategoryIcon from '../components/ui/CategoryIcon';
import Breadcrumbs from '../components/ui/Breadcrumbs';
import ServicesSection from '../components/home/ServicesSection';
import SEO from '../components/SEO';
import { Card, CardContent } from '@bettergov/kapwa/card';
import { Banner } from '@bettergov/kapwa/banner';
import { useState, useEffect } from 'react';

const emptyIndex: CategoryIndex = { layout: 'list', pages: [] };

const Services: React.FC = () => {
  const { category } = useParams();
  const [loaded, setLoaded] = useState<{
    category?: string;
    index: CategoryIndex;
  }>({ index: emptyIndex });

  const categoryData = serviceCategories.categories.find(
    c => c.slug === category
  );

  useEffect(() => {
    if (!category || !categoryData) return;
    let active = true;
    getCategorySubcategories(category)
      .then(index => {
        if (active) setLoaded({ category, index });
      })
      .catch(err => {
        console.error(err);
        if (active) setLoaded({ category, index: emptyIndex });
      });
    return () => {
      active = false;
    };
  }, [category, categoryData]);

  const loading = Boolean(
    category && categoryData && loaded.category !== category
  );
  const categoryIndex =
    loaded.category === category ? loaded.index : emptyIndex;
  const subcategories: Subcategory[] = categoryIndex.pages;

  if (!category) {
    return (
      <>
        <SEO
          title="Services"
          description={`Find government services in Siquijor. Get the documents, application steps, fees, and office contacts you need.`}
          keywords="government services, public services, local government, civic services"
        />
        <ServicesSection
          title={`Services & information`}
          description={`Find government services in Siquijor. Get the documents, application steps, fees, and office contacts you need.`}
        />
      </>
    );
  }
  if (!categoryData) {
    return (
      <Section className="p-3 mb-12">
        <Breadcrumbs className="mb-8" />
        <Banner
          type="error"
          title="Category not found"
          description="The category you are looking for does not exist."
          icon
        />
      </Section>
    );
  }

  return (
    <>
      <SEO
        title={categoryData.category || category}
        description={categoryData.description}
        keywords={`${categoryData.category}, government services, public services, local government`}
      />
      <Section className="p-3 mb-12">
        <Breadcrumbs className="mb-8" />
        <CategoryIcon
          name={categoryData.icon}
          className="h-8 w-8 mb-4 text-primary-600 rounded-md"
        />
        <Heading>{categoryData.category || category}</Heading>
        <Text className="text-gray-600 mb-6">{categoryData.description}</Text>

        {loading ? (
          <div className="flex justify-center items-center p-8">
            <Text>Loading services...</Text>
          </div>
        ) : (
          <>
            {categoryIndex.title && (
              <Heading level={3}>{categoryIndex.title}</Heading>
            )}
            {categoryIndex.description && (
              <Text className="text-gray-600 mb-4">
                {categoryIndex.description}
              </Text>
            )}
            {categoryIndex.layout === 'grid' ? (
              <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-3">
                {subcategories.map(subcategory => (
                  <Link
                    key={subcategory.slug}
                    aria-label={subcategory.name}
                    to={`/services/${category}/${subcategory.slug}`}
                  >
                    <Card
                      hoverable
                      className="h-full border-t-4 border-primary-500"
                    >
                      <CardContent>
                        <h4 className="text-lg font-medium text-gray-900">
                          {subcategory.name}
                        </h4>
                        {subcategory.description && (
                          <p className="mt-2 text-sm text-gray-600">
                            {subcategory.description}
                          </p>
                        )}
                        <span className="inline-block px-2 py-1 mt-2 text-xs font-medium rounded-sm bg-gray-100 text-gray-800">
                          {categoryData.category || category}
                        </span>
                      </CardContent>
                    </Card>
                  </Link>
                ))}
              </div>
            ) : (
              <div className="space-y-4">
                {subcategories.map(subcategory => (
                  <Link
                    key={subcategory.slug}
                    aria-label={subcategory.name}
                    to={`/services/${category}/${subcategory.slug}`}
                  >
                    <Card hoverable className="mb-4">
                      <CardContent>
                        <h4 className="text-lg font-medium text-gray-900">
                          {subcategory.name}
                        </h4>
                        {subcategory.description && (
                          <p className="mt-2 text-sm text-gray-600">
                            {subcategory.description}
                          </p>
                        )}
                        <span className="inline-block px-2 py-1 mt-2 text-xs font-medium rounded-sm bg-gray-100 text-gray-800">
                          {categoryData.category || category}
                        </span>
                      </CardContent>
                    </Card>
                  </Link>
                ))}
              </div>
            )}
          </>
        )}
      </Section>
    </>
  );
};

export default Services;

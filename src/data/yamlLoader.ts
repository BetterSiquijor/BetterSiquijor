import * as yaml from 'js-yaml';

// Type definitions for the services data
export interface Subcategory {
  name: string;
  slug: string;
  description?: string;
}

export interface Category {
  category: string;
  slug: string;
  description: string;
  icon: string;
  subcategories?: Subcategory[]; // Keep for backward compatibility
}

export interface CategoryData {
  categories: Category[];
  description: string;
}

export interface CategoryIndexData {
  title?: string;
  description?: string;
  layout?: 'grid' | 'list';
  pages: Subcategory[];
}

// Import the YAML file as raw text
import servicesYamlContent from './services.yaml?raw';
import governmentActivitiesYamlContent from './government.yaml?raw';

// Statically registered category indexes keep content routes explicit.
import categoryIndex0 from '../../content/services/health/index.yaml?raw';
import categoryIndex1 from '../../content/services/education/index.yaml?raw';
import categoryIndex2 from '../../content/services/civil-documents/index.yaml?raw';
import categoryIndex3 from '../../content/services/tourism/index.yaml?raw';
import categoryIndex4 from '../../content/government/departments/index.yaml?raw';
import categoryIndex5 from '../../content/government/municipalities/index.yaml?raw';
import categoryIndex6 from '../../content/government/transparency/index.yaml?raw';
import categoryIndex7 from '../../content/government/sources/index.yaml?raw';

const categoryIndexMap: { [key: string]: string } = {
  'health': categoryIndex0,
  'education': categoryIndex1,
  'civil-documents': categoryIndex2,
  'tourism': categoryIndex3,
  'departments': categoryIndex4,
  'municipalities': categoryIndex5,
  'transparency': categoryIndex6,
  'sources': categoryIndex7,
};

// Parse the YAML content
export const serviceCategories: CategoryData = yaml.load(
  servicesYamlContent
) as CategoryData;

export const governmentCategories: CategoryData = yaml.load(
  governmentActivitiesYamlContent
) as CategoryData;

export interface CategoryIndex {
  title?: string;
  description?: string;
  layout: 'grid' | 'list';
  pages: Subcategory[];
}

// Function to load category index data
export async function loadCategoryIndex(
  categorySlug: string
): Promise<CategoryIndex> {
  const yamlContent = categoryIndexMap[categorySlug];
  if (!yamlContent) {
    return { layout: 'list', pages: [] };
  }
  try {
    const indexData: CategoryIndexData = yaml.load(
      yamlContent
    ) as CategoryIndexData;
    return {
      title: indexData.title,
      description: indexData.description,
      layout: indexData.layout ?? 'list',
      pages: indexData.pages || [],
    };
  } catch (parseError) {
    console.warn(
      `Failed to parse YAML content for category ${categorySlug}:`,
      parseError
    );
    return { layout: 'list', pages: [] };
  }
}

// Function to get subcategories for a category (with caching)
const categoryCache = new Map<string, CategoryIndex>();

export async function getCategorySubcategories(
  categorySlug: string
): Promise<CategoryIndex> {
  if (categoryCache.has(categorySlug)) {
    return categoryCache.get(categorySlug)!;
  }

  const result = await loadCategoryIndex(categorySlug);
  categoryCache.set(categorySlug, result);
  return result;
}

/** Returns true if a slug has a registered index in categoryIndexMap */
export function isNestedCategory(slug: string): boolean {
  return slug in categoryIndexMap;
}
